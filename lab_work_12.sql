-- Практична робота 12. Сортування і фільтрація даних
-- Варіант 3. База даних кінотеатру
-- Таблиці: movies, viewers, tickets
-- Запити та фактичні результати виконання.

-- Завдання 1. Сортування за одним стовпцем у спадному порядку.
SELECT id, hall, showtime, price
FROM tickets
ORDER BY price DESC;

-- Результат:
-- (2, 2, '2026-09-30 19:30', 200.0)
-- (5, 1, '2026-10-02 20:00', 190.0)
-- (1, 1, '2026-09-30 18:00', 180.0)
-- (3, 1, '2026-10-01 17:00', 170.0)
-- (4, 3, '2026-10-01 15:00', 150.0)
-- Першим є квиток id=2, оскільки його ціна 200.0 — найбільша.

-- Завдання 2. Сортування за двома стовпцями.
SELECT id, hall, showtime, price
FROM tickets
ORDER BY hall ASC, showtime DESC;

-- Результат:
-- (5, 1, '2026-10-02 20:00', 190.0)
-- (3, 1, '2026-10-01 17:00', 170.0)
-- (1, 1, '2026-09-30 18:00', 180.0)
-- (2, 2, '2026-09-30 19:30', 200.0)
-- (4, 3, '2026-10-01 15:00', 150.0)
-- Спочатку записи впорядковано за номером залу за зростанням.
-- Усередині кожного залу сеанси впорядковуються за датою/часом за спаданням.

-- Завдання 3. Вибір трьох найдорожчих квитків.
SELECT id, hall, showtime, price
FROM tickets
ORDER BY price DESC
LIMIT 3;

-- Результат:
-- (2, 2, '2026-09-30 19:30', 200.0)
-- (5, 1, '2026-10-02 20:00', 190.0)
-- (1, 1, '2026-09-30 18:00', 180.0)
-- ORDER BY спочатку сортує всі записи за ціною, а LIMIT залишає перші три.

-- Завдання 4а. Унікальні жанри фільмів.
SELECT DISTINCT genre
FROM movies
ORDER BY genre;

-- Результат:
-- Animation
-- Drama
-- Fantasy
-- Sci-Fi
-- Усього унікальних жанрів: 4.

-- Завдання 4б. Вибір квитків у заданому діапазоні цін.
SELECT id, price
FROM tickets
WHERE price BETWEEN 150 AND 200
ORDER BY price;

-- Результат:
-- (4, 150.0)
-- (3, 170.0)
-- (1, 180.0)
-- (5, 190.0)
-- (2, 200.0)
-- BETWEEN використано, оскільки потрібно вибрати числовий діапазон,
-- включно з обома межами 150 і 200.

-- Завдання 5. Пошук прізвищ за першою літерою.
SELECT last_name
FROM viewers
WHERE last_name LIKE 'К%';

-- Результат:
-- Ковальчук
-- Кількість: 1.

SELECT last_name
FROM viewers
WHERE last_name LIKE 'к%';

