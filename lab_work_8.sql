-- =========================================================
-- Завдання 1
-- COUNT(*) проти COUNT(колонка)
-- =========================================================

-- До створення NULL:
SELECT COUNT(*) AS усі_рядки, COUNT(session_time) AS рядки_з_часом
FROM sessions;
-- Результат: 4 | 4

-- Один час сеансу навмисно змінено на NULL:
UPDATE sessions SET session_time = NULL WHERE id = 4;

SELECT COUNT(*) AS усі_рядки, COUNT(session_time) AS рядки_з_часом
FROM sessions;
-- Результат: 4 | 3

-- COUNT(*) рахує всі рядки, а COUNT(session_time) пропускає NULL.

-- =========================================================
-- Завдання 2
-- SUM і AVG
-- =========================================================

SELECT SUM(seats) AS загальна_кількість_місць,
       AVG(seats) AS середня_кількість_місць
FROM halls;
-- Результат: 330 | 110.0

-- SUM показує загальну кількість місць у всіх залах.
-- AVG показує середню кількість місць в одному залі.

-- =========================================================
-- Завдання 3
-- MIN/MAX для текстової колонки
-- =========================================================

SELECT MIN(title) AS перший_за_алфавітом,
       MAX(title) AS останній_за_алфавітом
FROM movies;
-- Результат: Інтерстеллар | Шрек

-- Для TEXT SQLite порівнює значення за правилами сортування тексту.

-- =========================================================
-- Завдання 4
-- Кілька агрегатних функцій
-- =========================================================

SELECT COUNT(*) AS кількість_сеансів,
       SUM(hall_id) AS сума_id_залів,
       AVG(hall_id) AS середній_id_залу,
       MIN(session_date) AS найраніша_дата,
       MAX(session_date) AS найпізніша_дата
FROM sessions;
-- Результат: 4 | 7 | 1.75 | 2026-10-07 | 2026-10-08

-- =========================================================
-- Завдання 5
-- Агрегат + WHERE
-- =========================================================

SELECT COUNT(*) AS кількість_сеансів,
       AVG(hall_id) AS середній_id_залу,
       MIN(session_date) AS найраніша_дата
FROM sessions
JOIN movies ON sessions.movie_id = movies.id
WHERE movies.genre = 'Фантастика';
-- Результат: 4 | 1.75 | 2026-10-07

-- WHERE залишає тільки сеанси фільмів жанру Фантастика,
-- тому агрегатні функції рахують не всі рядки, а лише відфільтровані.
