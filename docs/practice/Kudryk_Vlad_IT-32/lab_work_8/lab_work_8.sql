-- =====================================================================
-- ЗАВДАННЯ 1. COUNT(*) проти COUNT(колонка)
-- "Необов'язкова" (nullable) колонка у фактовій таблиці — client_id:
-- вона може стати NULL через ON DELETE SET NULL, якщо клієнта видалено.
-- =====================================================================
SELECT COUNT(*) AS всього_замовлень, COUNT(client_id) AS замовлень_з_клієнтом
FROM orders;
-- Результат до змін: 6 | 6 — числа збіглися, бо наразі жодного клієнта
-- не було видалено і client_id ніде не NULL.

-- Навмисно симулюємо видалення клієнта для одного замовлення:
UPDATE orders SET client_id = NULL WHERE id = 6;

SELECT COUNT(*) AS всього_замовлень, COUNT(client_id) AS замовлень_з_клієнтом
FROM orders;
-- Результат після змін: 6 | 5


-- =====================================================================
-- ЗАВДАННЯ 2. SUM і AVG на числовій колонці (price)
-- =====================================================================
SELECT SUM(price) AS сумарна_виручка, AVG(price) AS середній_чек
FROM orders;
-- Результат: 1068.0 | 178.0


-- =====================================================================
-- ЗАВДАННЯ 3. MIN/MAX на текстовій/датовій колонці (order_date)
-- =====================================================================
SELECT MIN(order_date) AS найперше_замовлення, MAX(order_date) AS останнє_замовлення
FROM orders;
-- Результат: '2026-09-01' | '2026-09-06'


-- =====================================================================
-- ЗАВДАННЯ 4. Кілька агрегатних функцій в одному запиті
-- =====================================================================
SELECT
    COUNT(*)      AS кількість_замовлень,
    SUM(price)    AS сумарна_виручка,
    AVG(price)    AS середній_чек,
    MIN(price)    AS мінімальна_ціна,
    MAX(price)    AS максимальна_ціна
FROM orders;
-- Результат: 6 | 1068.0 | 178.0 | 120.0 | 240.0


-- =====================================================================
-- ЗАВДАННЯ 5. Агрегат + WHERE на таблиці-вимірі
-- Середній чек лише по замовленнях з піцерії (restaurants.category = 'Піца')
-- =====================================================================
SELECT AVG(orders.price) AS середній_чек_піца
FROM orders
JOIN restaurants ON orders.restaurant_id = restaurants.id
WHERE restaurants.category = 'Піца';
-- Результат: 206.333... (середнє по трьох замовленнях з Pizza House:
-- 220.0, 240.0, 159.0; загальний середній чек без фільтра був 178.0)


-- =====================================================================
-- Контрольне питання 3. Що поверне SUM, якщо рядків узагалі немає
-- (еквівалент "усі значення NULL" з погляду SUM — вона просто не бачить
-- жодного числа для підсумовування)
-- =====================================================================
SELECT SUM(price) AS сума_неіснуючого_ресторану
FROM orders
WHERE restaurant_id = 9999;
-- Результат: NULL (не 0!)
