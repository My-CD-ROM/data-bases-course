-- навмисно залишає квиток №8 у фінальному стані бази.

-- =========================================================
-- Завдання 1. Атомарна пара INSERT + UPDATE
-- Додаємо квиток для глядача №2 та оновлюємо його email.
-- =========================================================
BEGIN;

INSERT INTO tickets
    (id, movie_id, viewer_id, hall, showtime, price, seat, purchase_date)
VALUES
    (6, 6, 2, 2, '2026-10-03 18:00', 210.0, 'B6', '2026-10-01');

UPDATE viewers
SET email = 'maksym.updated@example.com'
WHERE id = 2;

COMMIT;

-- Перевірка:
SELECT * FROM tickets WHERE id = 6;
-- Результат:
-- (6, 6, 2, 2, '2026-10-03 18:00', 210.0, 'B6', '2026-10-01')

SELECT id, first_name, email FROM viewers WHERE id = 2;
-- Результат:
-- (2, 'Максим', 'maksym.updated@example.com')


-- =========================================================
-- Завдання 2. Свідомий ROLLBACK
-- Тимчасово змінюємо ціну квитка №6, потім скасовуємо зміну.
-- =========================================================
BEGIN;

UPDATE tickets
SET price = 999.0
WHERE id = 6;

SELECT id, price FROM tickets WHERE id = 6;
-- Усередині транзакції: (6, 999.0)

ROLLBACK;

SELECT id, price FROM tickets WHERE id = 6;
-- Після ROLLBACK: (6, 210.0)


-- =========================================================
-- Завдання 3. Проміжний стан усередині транзакції
-- Зміна видима в тій самій сесії до COMMIT.
-- Для збереження узгодженого фінального стану скасовуємо її.
-- =========================================================
BEGIN;

UPDATE tickets
SET price = 220.0
WHERE id = 6;

SELECT id, price FROM tickets WHERE id = 6;
-- Результат до завершення транзакції: (6, 220.0)

ROLLBACK;


-- =========================================================
-- Завдання 4. Свідома помилка всередині транзакції
-- Перша команда додає квиток №7.
-- Друга команда порушує PRIMARY KEY (id = 1 вже існує).
-- Помилка SQLite:
-- UNIQUE constraint failed: tickets.id
-- Перша зміна видима до ROLLBACK, але потім скасовується.
-- =========================================================
BEGIN;

INSERT INTO tickets
    (id, movie_id, viewer_id, hall, showtime, price, seat, purchase_date)
VALUES
    (7, 5, 1, 1, '2026-10-04 16:00', 160.0, 'A3', '2026-10-02');

-- Наступний INSERT навмисно завершується помилкою UNIQUE.
-- У разі запуску всього файлу клієнт SQLite може зупинити виконання
-- на цій команді; для демонстрації помилки виконуйте її окремо.
INSERT INTO tickets
    (id, movie_id, viewer_id, hall, showtime, price, seat, purchase_date)
VALUES
    (1, 1, 1, 1, '2026-10-05 18:00', 180.0, 'A4', '2026-10-03');

SELECT * FROM tickets WHERE id = 7;
-- Результат до ROLLBACK:
-- (7, 5, 1, 1, '2026-10-04 16:00', 160.0, 'A3', '2026-10-02')

ROLLBACK;

SELECT * FROM tickets WHERE id = 7;
-- Результат після ROLLBACK: порожній набір.


-- =========================================================
-- Завдання 5. COMMIT після помилки
-- Перша команда додає квиток №8.
-- Друга команда знову порушує PRIMARY KEY (id = 1).
-- Помилка не скасовує автоматично всю транзакцію.
-- COMMIT фіксує успішну першу команду.
-- =========================================================
BEGIN;

INSERT INTO tickets
    (id, movie_id, viewer_id, hall, showtime, price, seat, purchase_date)
VALUES
    (8, 5, 3, 3, '2026-10-06 14:00', 155.0, 'D5', '2026-10-04');

-- Наступний INSERT навмисно завершується помилкою UNIQUE.
INSERT INTO tickets
    (id, movie_id, viewer_id, hall, showtime, price, seat, purchase_date)
VALUES
    (1, 1, 1, 1, '2026-10-07 18:00', 180.0, 'A5', '2026-10-05');

COMMIT;

SELECT * FROM tickets WHERE id IN (1, 8) ORDER BY id;
-- Результат:
-- Початковий квиток №1 залишається без змін.
-- Новий квиток №8 збережено:
-- (8, 5, 3, 3, '2026-10-06 14:00', 155.0, 'D5', '2026-10-04')


-- =========================================================
-- Фінальна перевірка бази
-- =========================================================
SELECT id, viewer_id, price, seat
FROM tickets
ORDER BY id;

