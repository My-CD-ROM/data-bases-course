-- ============================================================
-- Завдання 5. Письмове пояснення обраних типів (type affinity)
-- ============================================================
-- id (INTEGER PRIMARY KEY):
--   Цілочисельний сурогатний ключ. У SQLite стовпець з таким
--   оголошенням стає псевдонімом внутрішнього rowid і отримує
--   автоматичне унікальне значення при кожному INSERT без
--   потреби вказувати AUTOINCREMENT.
--
-- name, manufacturer, form (TEXT):
--   Це рядкові дані змінної довжини (назви, виробники, форма
--   випуску). Над ними не виконуються арифметичні операції,
--   тому TEXT — єдиний логічний вибір; SQLite не обмежує
--   довжину рядка окремим типом VARCHAR(n), як PostgreSQL.
--
-- price (REAL):
--   Ціна може містити дробову частину (копійки), тому потрібен
--   тип з рухомою комою. INTEGER втратив би копійки, TEXT
--   унеможливив би коректне сортування й обчислення (наприклад,
--   суми чи знижки).
--
-- stock_quantity (INTEGER):
--   Кількість одиниць товару на складі завжди ціла (не можна
--   мати "3.5 упаковки"), тому INTEGER коректно відображає
--   природу даних і дозволяє арифметику (списання, поповнення)
--   без ризику дробових залишків.
--
-- ============================================================
-- Контрольні питання
-- ============================================================
--
-- 1. Чому SQLite називають файловою, безсерверною СУБД?
--    Уся база даних (схема, дані, індекси) зберігається в
--    одному звичайному файлі на диску (apteka.db), і немає
--    окремого процесу-сервера, до якого треба підключатися по
--    мережі. Бібліотека SQLite вбудовується прямо в застосунок
--    (або в CLI-утиліту), яка сама читає й пише в цей файл.
--    Практично це означає: файл можна скопіювати, перенести на
--    інший комп'ютер чи покласти у Git — і база "переїде" разом
--    з ним, без встановлення сервера й налаштування облікових
--    записів чи портів.
--
-- 2. Різниця між sqlite3 (CLI) і DB Browser for SQLite:
--    CLI sqlite3 — це текстовий інтерфейс: швидко виконувати
--    SQL-команди, писати скрипти, автоматизувати роботу (як цей
--    файл). DB Browser for SQLite — графічний інтерфейс: зручно
--    візуально переглядати таблиці, редагувати дані вручну "як
--    у таблиці Excel", будувати структуру через форми без
--    написання SQL. CLI зручніший для скриптів і автоматизації,
--    DB4S — для наочного перегляду й ручного редагування.
--
-- 3. Що таке type affinity і чим відрізняється від PostgreSQL:
--    Type affinity — це "рекомендований" тип стовпця в SQLite:
--    сам механізм зберігання даних (storage class) динамічний,
--    і в стовпець будь-якого оголошеного типу технічно можна
--    записати значення іншого типу (наприклад, текст у REAL-
--    стовпець). Affinity лише підказує, до якого типу SQLite
--    намагатиметься привести значення при вставці. У PostgreSQL
--    типізація сувора (статична): якщо стовпець оголошено як
--    INTEGER, спроба вставити туди текст, який не можна
--    привести до числа, викличе помилку — контроль типів
--    відбувається жорстко на рівні СУБД, а не як рекомендація.
--
-- 4. id INTEGER PRIMARY KEY vs звичайний стовпець INTEGER:
--    Стовпець id INTEGER PRIMARY KEY у SQLite стає прямим
--    псевдонімом внутрішнього rowid — значення унікальне,
--    автоматично генерується (наступне вільне ціле), і NULL
--    при INSERT замінюється на нього автоматично. Звичайний
--    стовпець типу INTEGER (без PRIMARY KEY) не має жодної з
--    цих властивостей: значення можуть повторюватися, бути
--    NULL, і жодного автоматичного заповнення не відбувається.