-- ---------- Завдання 1. Створення таблиці ----------
-- Типи обрано за принципом type affinity SQLite:
--   id                INTEGER PRIMARY KEY -- ціле число, автоінкрементний
--                                          -- сурогатний ключ (rowid-псевдонім)
--   name              TEXT     -- назва препарату — рядок довільної довжини,
--                               -- арифметичні операції над нею не потрібні
--   manufacturer      TEXT     -- назва виробника — теж текст, не число
--   form              TEXT     -- форма випуску (таблетки, сироп, мазь...) —
--                               -- обмежений, але текстовий набір значень
--   price             REAL     -- ціна — дробове число (гривні з копійками),
--                               -- потрібні арифметичні операції й сортування
--   stock_quantity    INTEGER  -- кількість одиниць на складі — завжди ціле,
--                               -- дробової упаковки не існує
CREATE TABLE medicines (
    id                 INTEGER PRIMARY KEY,
    name               TEXT NOT NULL,
    manufacturer       TEXT NOT NULL,
    form               TEXT NOT NULL,
    price              REAL NOT NULL,
    stock_quantity     INTEGER NOT NULL
);

-- ---------- Завдання 2. Наповнення даними ----------
