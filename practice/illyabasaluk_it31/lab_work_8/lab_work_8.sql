-- ==========================================
-- Завдання 1. COUNT(*) проти COUNT(колонка)
-- ==========================================

SELECT
    COUNT(*) AS всього_позик,
    COUNT(return_date) AS позик_з_датою_повернення
FROM loans;

-- Результат: 9, 7
-- 9 — загальна кількість позик.
-- 7 — кількість позик, які мають дату повернення.
-- 2 записи мають NULL у return_date.


-- ==========================================
-- Завдання 2. SUM і AVG
-- ==========================================

SELECT
    SUM(copies_count) AS загальна_кількість_примірників,
    AVG(copies_count) AS середня_кількість_примірників
FROM books;

-- Результат: 29, 3.625
-- 29 — загальна кількість примірників усіх книг.
-- 3.625 — середня кількість примірників однієї книги.


-- ==========================================
-- Завдання 3. MIN і MAX
-- ==========================================

SELECT
    MIN(loan_date) AS найраніша_дата_видачі,
    MAX(loan_date) AS найпізніша_дата_видачі
FROM loans;

-- Результат: 2026-09-10, 2026-09-18
-- MIN визначає найменше значення дати,
-- а MAX — найбільше значення дати.


-- ==========================================
-- Завдання 4. Кілька агрегатних функцій
-- ==========================================

SELECT
    COUNT(*) AS загальна_кількість_позик,
    COUNT(return_date) AS кількість_повернених,
    MIN(loan_date) AS найраніша_дата,
    MAX(loan_date) AS найпізніша_дата,
    COUNT(DISTINCT book_id) AS різних_книг
FROM loans;

-- Результат:
-- 9, 7, 2026-09-10, 2026-09-18, 6


-- ==========================================
-- Завдання 5. Агрегат + WHERE
-- ==========================================

SELECT
    COUNT(*) AS кількість_позик,
    COUNT(loans.return_date) AS кількість_повернених,
    COUNT(DISTINCT loans.book_id) AS різних_книг
FROM loans
INNER JOIN books
    ON loans.book_id = books.id
WHERE books.author = 'Тарас Шевченко';

-- Результат: 2, 1, 1
-- WHERE залишає тільки позики книг автора Тарас Шевченко.